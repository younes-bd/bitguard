class TranslationViewSet(TenantScopedMixin, viewsets.ModelViewSet):
    queryset = Translation.objects.all()
    serializer_class = TranslationSerializer
    permission_classes = [permissions.IsAuthenticated]
    
    def get_permissions(self):
        if self.action == 'locales':
            return []
        return super().get_permissions()

    @action(detail=False, methods=['get'], permission_classes=[])
    def locales(self, request):
        lng = request.query_params.get('lng', 'en')
        # Return translations mapped name: value
        translations = Translation.objects.filter(language__code=lng)
        
        # In a real multi-tenant scenario we might also filter by tenant,
        # but for public login screen, we might need a generic or domain-based tenant lookup.
        # For now, just return all matching or base ones.
        
        data = {t.name: t.value for t in translations}
        return Response(data)

    @action(detail=False, methods=['get'])
    def export(self, request):
        from django.http import HttpResponse
        language = request.query_params.get('language', 'en')
        fmt = request.query_params.get('format', 'po')
        tenant = getattr(request.user, 'tenant', None)
        
        lines = []
        lines.append(f'# Translation file for language: {language}')
        lines.append(f'# Generated by BitGuard ERP')
        lines.append(f'# Format: {fmt}')
        lines.append('')
        
        try:
            translations = Translation.objects.filter(tenant=tenant, language__code=language)
            for t in translations:
                lines.append(f'msgid "{t.name}"')
                lines.append(f'msgstr "{t.value}"')
                lines.append('')
        except Exception:
            pass
        
        content = '\n'.join(lines)
        content_type = 'text/x-po' if fmt == 'po' else 'text/csv'
        ext = fmt if fmt in ['po', 'csv'] else 'po'
        response = HttpResponse(content, content_type=f'{content_type}; charset=utf-8')
        response['Content-Disposition'] = f'attachment; filename="translations_{language}.{ext}"'
        return response

