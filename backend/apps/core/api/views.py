        writer = csv.writer(response)
        writer.writerow(['Date', 'User', 'Action', 'Resource', 'Details'])
        for log in queryset:
            writer.writerow([log.created_at, log.user.email if log.user else 'System', log.action, log.resource_type, log.details])
        return response

